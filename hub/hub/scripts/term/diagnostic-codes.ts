// The diagnostic code vocabulary: a failure's code leaves a mount (receipt, the line in the
// user's terminal) only when it is a code the Hub's own source names as a literal: `'TERM_SESSION_ENDED'`,
// `new Error('TERM_X: …')`, a route's `codes: ['…']`, the API's catalogue (src/core/error-codes.gen.ts). Anything else (a server string, an error's text, a secret shaped
// like a code) is UNHANDLED. `bun scripts/term/diagnostic-codes.ts` writes src/term/app/diagnostic-codes.gen.ts;
// src/term/app/diagnostic.term.test.ts fails while the file differs from a fresh scan. A TERM_ code built at run time
// (`'TERM_X_' + state`) would reach the vocabulary only as its bare prefix, so every value would leave as UNHANDLED:
// the scan refuses a bare TERM_ prefix in the source (termPrefixLiterals) until each code is written out whole.
import './netns-first'; // the OS boundary before anything else (netns.term.test.ts 'every entry')
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const CODE_LITERAL = /['"`]([A-Z][A-Z0-9_]{2,63})(?=['"`:])/g;
const SKIP_DIR = new Set(['node_modules', 'fixtures', 'gallery', 'demo', 'test', '__tests__']);
// Generated files are skipped except the API's own code catalogue (src/core/error-codes.gen.ts): server codes count.
const SKIP_FILE = /(\.test\.|\.spec\.|\.fixtures\.|\/fixtures\.ts$|\/world\.ts$|\/testing\.ts$|diagnostic-codes\.gen\.ts$|\.scenario\.ts$)/;

/** The source text of every string and template literal of `text` (parsed, so a quoted word in a comment or in JSX
 *  text, `it drew "HOOD"` in TermShell.tsx, is prose and never a code). */
export function literalTexts(text: string, file: string): string[] {
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, false, /x$/.test(file) ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const out: string[] = [];
  const visit = (n: ts.Node): void => {
    if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n) || ts.isTemplateHead(n) || ts.isTemplateMiddle(n) || ts.isTemplateTail(n)) out.push(n.getText(sf));
    ts.forEachChild(n, visit);
  };
  visit(sf);
  return out;
}

// A bare TERM_ prefix: a code family's start that the source would complete at run time.
const TERM_PREFIX = /^TERM_(?:[A-Z0-9_]*_)?$/;

/** `line: 'PREFIX'` for each value in `text` that is a bare TERM_ prefix: a string literal (`'TERM_BOOT_' + state`,
 *  `'TERM_BOOT_'.concat(state)`, `const P = 'TERM_BOOT_'`) or a template's head (`` `TERM_BOOT_${state}` ``). Whatever
 *  completes it, the code is not a literal, so the scan cannot list it. Types (a template literal type) are not values. */
export function termPrefixLiterals(text: string, file: string): string[] {
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, false, /x$/.test(file) ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const out: string[] = [];
  const at = (n: ts.Node, prefix: string): void => { out.push(`${sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1}: '${prefix}'`); };
  const visit = (n: ts.Node): void => {
    if ((ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) && TERM_PREFIX.test(n.text)) at(n, n.text);
    if (ts.isTemplateExpression(n) && TERM_PREFIX.test(n.head.text)) at(n, n.head.text);
    ts.forEachChild(n, visit);
  };
  visit(sf);
  return out;
}

/** Every code-shaped string literal in the Hub's non-test, non-fixture source under `src`, sorted. Throws when that
 *  source holds a bare TERM_ prefix (termPrefixLiterals). */
export function scanDiagnosticCodes(src: string): string[] {
  const out = new Set<string>(['UNHANDLED']);
  const built: string[] = [];
  const walk = (dir: string): void => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (!SKIP_DIR.has(e.name)) walk(p); continue; }
      if (!/\.(ts|tsx|mts)$/.test(e.name) || SKIP_FILE.test(p)) continue;
      const text = fs.readFileSync(p, 'utf8');
      for (const lit of literalTexts(text, p)) for (const m of lit.matchAll(CODE_LITERAL)) out.add(m[1]!);
      for (const b of termPrefixLiterals(text, p)) built.push(`${path.relative(src, p)}:${b}`);
    }
  };
  walk(src);
  // Whatever form put it there (a `CODE:` message on a prefix, a form the walk above does not see), a TERM_ entry
  // ending in `_` is a prefix, never a code.
  for (const c of out) if (c.startsWith('TERM_') && c.endsWith('_')) built.push(`vocabulary: '${c}'`);
  if (built.length > 0) throw new Error(`diagnostic codes: a TERM_ code built at run time from a bare prefix never reaches the vocabulary (it leaves the mount as UNHANDLED); write each code out whole:\n  ${built.join('\n  ')}`);
  return [...out].sort();
}

export function renderDiagnosticCodes(codes: readonly string[]): string {
  return '// GENERATED by scripts/term/diagnostic-codes.ts: never edit by hand (re-run the script).\n' +
    '// The codes a terminal diagnostic may carry (src/term/app/diagnostic.ts codeOf); any other is UNHANDLED.\n' +
    'export const DIAGNOSTIC_CODES: ReadonlySet<string> = new Set([\n' + codes.map((c) => `  '${c}',`).join('\n') + '\n]);\n';
}

export const GEN_FILE = path.join(import.meta.dir, '../../src/term/app/diagnostic-codes.gen.ts');

if (import.meta.main) {
  const codes = scanDiagnosticCodes(path.join(import.meta.dir, '../../src'));
  fs.writeFileSync(GEN_FILE, renderDiagnosticCodes(codes));
  console.log(`diagnostic codes: ${codes.length} -> ${path.relative(process.cwd(), GEN_FILE)}`);
}
