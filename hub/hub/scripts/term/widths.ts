// The cell-width table of runtimes without Bun (src/term/prim/widths.gen.ts, read by src/term/prim/width.ts): Bun's
// own Bun.stringWidth, asked once per code point and for the few emoji sequences whose width depends on what follows.
// Under Bun the Hub measures with Bun.stringWidth itself; under Node the same bundle reads this table, so both runtimes
// lay text out on the same cells.
//
//   bun scripts/term/widths.ts            writes src/term/prim/widths.gen.ts
//
// Run it with Bun (the table is Bun's answer). src/term/prim/width.term.test.ts fails while the file differs from a
// fresh run, so a Bun upgrade that changes a width shows up there.
import './netns-first'; // the OS boundary before anything else (netns.term.test.ts 'every entry')
import fs from 'node:fs';
import path from 'node:path';

export const WIDTHS_FILE = path.join(import.meta.dirname, '..', '..', 'src', 'term', 'prim', 'widths.gen.ts');

const ZWJ = '\u200d';
const VS16 = '\ufe0f';
const LAPTOP = '\u{1f4bb}';
const SKIN = '\u{1f3fd}';
const PICTOGRAPHIC = /\p{Extended_Pictographic}/u;
const EMOJI = /\p{Emoji}/u;

interface Sets { ZERO: number[]; WIDE: number[]; PICTOGRAPHIC: number[]; JOINS: number[]; VS16_WIDE: number[]; SKIN_BASE: number[] }

const DOCS: Record<keyof Sets, string> = {
  ZERO: 'Code points that take no cell.',
  WIDE: 'Code points that take two cells.',
  PICTOGRAPHIC: 'Extended_Pictographic code points: what a ZWJ joins into the emoji before it.',
  JOINS: 'Bases after which a ZWJ makes one emoji of two cells (an emoji followed by ZWJ and another emoji).',
  VS16_WIDE: 'One-cell code points that take two cells when VS16 (U+FE0F) follows.',
  SKIN_BASE: 'Bases a skin-tone modifier joins (one emoji of two cells, the modifier takes none).',
};

/** The sets, each as sorted [first, last, first, last, ...] ranges. Bun only. */
export function widthSets(): Sets {
  const width = (globalThis as unknown as { Bun?: { stringWidth?(s: string): number } }).Bun?.stringWidth;
  if (!width) throw new Error('widths.ts runs under Bun: the table is what Bun.stringWidth answers');
  const sets: Sets = { ZERO: [], WIDE: [], PICTOGRAPHIC: [], JOINS: [], VS16_WIDE: [], SKIN_BASE: [] };
  const add = (k: keyof Sets, cp: number): void => {
    const a = sets[k];
    if (a.length && a[a.length - 1] === cp - 1) a[a.length - 1] = cp;
    else a.push(cp, cp);
  };
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const c = String.fromCodePoint(cp);
    const w = width(c);
    if (w === 0) add('ZERO', cp);
    else if (w === 2) add('WIDE', cp);
    else if (w !== 1) throw new Error(`Bun.stringWidth(U+${cp.toString(16)}) = ${w}: the table holds widths 0, 1 and 2 only`);
    const pict = PICTOGRAPHIC.test(c);
    if (pict) add('PICTOGRAPHIC', cp);
    if (!pict && !EMOJI.test(c)) continue;
    if (width(c + ZWJ + LAPTOP) === 2) add('JOINS', cp);
    if (w === 1 && width(c + VS16) === 2) add('VS16_WIDE', cp);
    if (width(c + SKIN) === 2) add('SKIN_BASE', cp);
  }
  return sets;
}

/** The text of widths.gen.ts. */
export function widthsSource(sets: Sets = widthSets()): string {
  const out = [
    '// GENERATED by `bun scripts/term/widths.ts` from Bun.stringWidth. Do not edit: run the script again.',
    '// Each list holds sorted ranges of code points: [first, last, first, last, ...]. Read by width.ts.',
  ];
  for (const k of Object.keys(DOCS) as (keyof Sets)[]) {
    out.push('', `/** ${DOCS[k]} */`, `export const ${k}: readonly number[] = [`);
    let line = '';
    for (const n of sets[k]) {
      const item = `${n},`;
      if (line.length + item.length + 1 > 116) { out.push(`  ${line.trimEnd()}`); line = ''; }
      line += `${item} `;
    }
    if (line) out.push(`  ${line.trimEnd()}`);
    out.push('];');
  }
  return out.join('\n') + '\n';
}

if (import.meta.main) {
  fs.writeFileSync(WIDTHS_FILE, widthsSource());
  process.stdout.write(`wrote ${path.relative(process.cwd(), WIDTHS_FILE)}\n`);
}
