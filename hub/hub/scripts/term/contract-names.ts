#!/usr/bin/env bun
// contract-names.ts: generates src/term/kit/contract.names.gen.ts, the kinds of the web kit's value exports that the
// graph gate reads (graph.ts: component / hook / value of every `@kit` barrel name; R6 "kit barrel exports X, which
// contract.names.gen.ts does not list" means this file is stale). Read with the TypeScript checker from
// src/kit/index.ts: a capitalised value whose every call signature returns a ReactNode (or a React exotic) is a
// component (generic when it has type parameters), `use` + capital is a hook, the rest are values. Type-only exports
// are not listed.
//   bun scripts/term/contract-names.ts            exit 1 when the committed file differs from a fresh run
//   bun scripts/term/contract-names.ts --write    rewrite it (review the diff)
// contract-names.term.test.ts checks that the committed file equals a fresh run. (Port of the retired
// src/term/kit/parity/{surface,names}.ts; the terminal-kit lists it also wrote had no reader and are gone.)
import './netns-first'; // the OS boundary before anything else (netns.term.test.ts 'every entry')
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { HUB } from './resolve';

export const NAMES_FILE = 'src/term/kit/contract.names.gen.ts';
export const KIT_ENTRY = 'src/kit/index.ts';

export interface Surface { components: string[]; generic: string[]; hooks: string[]; values: string[] }

/** The value surface of `entry` (hub-relative), compiled with the hub's own tsconfig. */
export function kitSurface(hub: string = HUB, entry: string = KIT_ENTRY): Surface {
  const configPath = path.join(hub, 'tsconfig.json');
  const parsed = ts.getParsedCommandLineOfConfigFile(configPath, {}, { ...ts.sys, onUnRecoverableConfigFileDiagnostic: () => {} });
  if (!parsed) throw new Error(`TERM_CONTRACT_NAMES: cannot read ${configPath}`);
  const program = ts.createProgram({ rootNames: [path.join(hub, entry)], options: { ...parsed.options, noEmit: true } });
  const checker = program.getTypeChecker();
  const file = program.getSourceFile(path.join(hub, entry));
  const mod = file && checker.getSymbolAtLocation(file);
  if (!file || !mod) throw new Error(`TERM_CONTRACT_NAMES: ${entry} is not a module in the program`);
  let reactNode: ts.Type | undefined;
  const reactNodeType = (): ts.Type => {
    if (reactNode) return reactNode;
    for (const sf of program.getSourceFiles()) {
      if (!/[\\/]@types[\\/]react[\\/]index\.d\.ts$/.test(sf.fileName)) continue;
      const m = checker.getSymbolAtLocation(sf);
      const sym = m && checker.getExportsOfModule(m).find((s) => s.name === 'ReactNode');
      if (sym) return (reactNode = checker.getDeclaredTypeOfSymbol(sym));
    }
    throw new Error('TERM_CONTRACT_NAMES: @types/react ReactNode is not in the program');
  };
  const out: Surface = { components: [], generic: [], hooks: [], values: [] };
  for (const s of checker.getExportsOfModule(mod)) {
    const symbol = s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s;
    if (!(symbol.flags & ts.SymbolFlags.Value)) continue;
    const type = checker.getTypeOfSymbolAtLocation(symbol, file);
    const sigs = type.getCallSignatures();
    const renders = type.getProperty('$$typeof') !== undefined
      || (sigs.length > 0 && sigs.every((g) => checker.isTypeAssignableTo(checker.getReturnTypeOfSignature(g), reactNodeType())));
    if (/^use[A-Z]/.test(s.name)) out.hooks.push(s.name);
    else if (/^[A-Z][a-z]/.test(s.name) && renders) (sigs.some((g) => (g.typeParameters?.length ?? 0) > 0) ? out.generic : out.components).push(s.name);
    else out.values.push(s.name);
  }
  for (const list of Object.values(out)) list.sort();
  return out;
}

const list = (name: string, items: readonly string[], doc: string): string =>
  `/** ${doc} */\nexport const ${name} = [${items.length ? `\n${items.map((i) => `  '${i}',`).join('\n')}\n` : ''}] as const;\n`;

export function renderNames(web: Surface): string {
  return [
    '// Generated by hub/scripts/term/contract-names.ts from the web kit barrel (src/kit/index.ts): regenerate with',
    '// `bun scripts/term/contract-names.ts --write`, never edit by hand. The graph gate reads the kinds (graph.ts).\n',
    list('WEB_COMPONENTS', web.components, 'Web kit components (non-generic).'),
    list('GENERIC_COMPONENTS', web.generic, 'Web kit components with type parameters.'),
    list('WEB_HOOKS', web.hooks, 'Web kit hooks.'),
    list('WEB_VALUES', web.values, 'Web kit constants and functions.'),
  ].join('\n');
}

if (import.meta.main) {
  const want = renderNames(kitSurface());
  const file = path.join(HUB, NAMES_FILE);
  const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (process.argv.includes('--write')) {
    if (have !== want) fs.writeFileSync(file, want);
    process.stdout.write(`contract-names: ${have === want ? 'unchanged' : 'written'} ${NAMES_FILE}\n`);
  } else if (have !== want) {
    process.stdout.write(`contract-names: ${NAMES_FILE} is stale; run \`bun scripts/term/contract-names.ts --write\` and review the diff\n`);
    process.exit(1);
  } else process.stdout.write(`contract-names: ${NAMES_FILE} is current\n`);
}
